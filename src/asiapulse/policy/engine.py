def positive_deviance(panel: pd.DataFrame, kpi: str, better: int, exclude: str, years: int = 10,
                      pool: list[str] | None = None, n: int = 3) -> list[dict]:
    """Economies with the largest improvement in ``kpi`` over the last ``years`` years."""
    if kpi not in panel.columns:
        return []
    # For inflation, "better" means closer to a ~3% target, not simply lower (deflation is not success).
    transform = (lambda x: -abs(x - 3.0)) if kpi == "inflation" else (lambda x: x * better)
    rows = []
    for iso, g in panel[kpi].groupby(level="iso3"):
        if iso == exclude or (pool is not None and iso not in pool):
            continue
        s = g.droplevel("iso3").dropna()
        if len(s) < 4:
            continue
        end_y = int(s.index.max())
        start = s[s.index <= end_y - years + 2]
        if start.empty:
            continue
        sy = int(start.index.max())
        change = float(s.loc[end_y] - start.loc[sy])
        rows.append({"iso3": iso, "country": ISO_TO_NAME.get(iso, iso), "from_year": sy, "to_year": end_y,
                     "from": float(start.loc[sy]), "to": float(s.loc[end_y]), "change": change,
                     "improvement": transform(float(s.loc[end_y])) - transform(float(start.loc[sy]))})
    rows.sort(key=lambda r: r["improvement"], reverse=True)
    return [r for r in rows if r["improvement"] > 0][:n]


