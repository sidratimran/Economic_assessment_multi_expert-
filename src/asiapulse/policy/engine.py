def _pillar_driver(pillar: str, iso: str, snap: pd.DataFrame) -> tuple[str | None, str | None]:
    """The indicator that contributes most to a pillar's vulnerability: (feature, readable text with value)."""
    feats = _features(snap)
    best, best_score = None, -1.0
    for feat, d in PILLARS.get(pillar, []):
        if feat not in feats or pd.isna(feats.loc[iso].get(feat, np.nan)):
            continue
        sc = _pct_vuln(float(feats.loc[iso, feat]), feats[feat], d)
        if sc > best_score:
            best, best_score = feat, sc
    if best is None:
        return None, None
    key, lab, unit = DRIVER_LABELS.get(best, (best, BY_KEY[best].label if best in BY_KEY else best,
                                                 BY_KEY[best].unit if best in BY_KEY else ""))
    val = snap.loc[iso].get(key, np.nan)
    return best, (f"{lab[0].lower() + lab[1:]} ({val:.1f} {unit})" if pd.notna(val) else lab)


def recommend(iso: str, snap: pd.DataFrame, scores: pd.DataFrame, flags: pd.DataFrame,
              panel: pd.DataFrame, clusters: pd.DataFrame, top_n: int = 5) -> list[dict]:
    row = snap.loc[iso]
    srow = scores.loc[iso]
    my_flags = flags[flags.iso3 == iso].to_dict("records") if len(flags) else []
    flag_lookup = {f.key: f for f in FLAGS}
    candidates: dict[str, dict] = {}

    for f in my_flags:
        play = PLAYBOOK.get(f["key"])
        if not play:
            continue
        thr = flag_lookup[f["key"]].threshold
        dist = abs(f["value"] - thr) / max(abs(thr), 1.0)
        severity = min(100.0, 50 + 50 * dist)
        pillar_score = srow.get(f"pillar_{f['pillar']}", 50)
        candidates[play.key] = {"play": play, "trigger": f["text"], "trigger_value": f["value"],
                                "pillar": f["pillar"], "severity": severity,
                                "priority": 0.6 * severity + 0.4 * (pillar_score if pd.notna(pillar_score) else 50)}

    # Weak pillars without a flag still get a recommendation.
    for col in [c for c in scores.columns if c.startswith("pillar_")]:
        p = col.replace("pillar_", "")
        v = srow[col]
        pillar_has_flag = any(c["pillar"] == p for c in candidates.values())
        if pd.isna(v) or v < 60 or pillar_has_flag:
            continue
        feat, driver = _pillar_driver(p, iso, snap)
        key = DRIVER_PLAY.get(feat) or PILLAR_DEFAULT_PLAY.get(p)
        if key and key in PLAYBOOK and key not in candidates:
            play = PLAYBOOK[key]
            why = f" — driven by {driver}" if driver else ""
            candidates[key] = {"play": play, "trigger": f"{pillar_label(p)} pillar is in Asia's most vulnerable 40% (score {v:.0f}/100){why}",
                               "trigger_value": None, "pillar": p, "severity": v, "priority": 0.9 * v}

    # Precedents must be stable economies: an indicator can "improve" through collapse (e.g. debt ratios in war).
    stable = snap.index[snap.get("political_stability", pd.Series(0, index=snap.index)).fillna(0) >= -1.0].tolist()
    my_cluster = clusters.loc[iso, "cluster"] if iso in clusters.index else None
    cluster_pool = clusters.index[clusters.cluster == my_cluster].tolist() if my_cluster is not None else None
    out = []
    for c in sorted(candidates.values(), key=lambda d: d["priority"], reverse=True)[:top_n]:
        play: Play = c["play"]
        kpi_now = row.get(play.kpi, np.nan)
        best_peer = None
        if play.kpi in snap.columns and cluster_pool:
            vals = snap.loc[[i for i in cluster_pool if i != iso], play.kpi].dropna()
            if len(vals):
                best_peer = float(vals.quantile(0.75 if play.kpi_better > 0 else 0.25))
        precedents = positive_deviance(panel, play.kpi, play.kpi_better, iso, pool=stable)
        out.append({
            "key": play.key, "title": play.title, "objective": play.objective, "actions": list(play.actions),
            "trigger": c["trigger"], "pillar": pillar_label(c["pillar"]), "priority": round(c["priority"], 1),
            "horizon": play.horizon, "lead": play.lead, "sdgs": list(play.sdgs),
            "kpi": play.kpi, "kpi_label": BY_KEY[play.kpi].label if play.kpi in BY_KEY else play.kpi,
            "kpi_now": None if pd.isna(kpi_now) else round(float(kpi_now), 2),
            "kpi_peer_target": None if best_peer is None else round(best_peer, 2),
            "precedents": precedents, "lever": play.lever,
        })
    return out
